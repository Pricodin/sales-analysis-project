"""Retail sales analysis: understand -> clean -> EDA -> charts -> report.
Every number in outputs/report.md is computed here (nothing typed by hand)."""
import matplotlib; matplotlib.use("Agg")
import pandas as pd, numpy as np, matplotlib.pyplot as plt, seaborn as sns
sns.set_theme(style="whitegrid")
CH = "outputs/charts/"

# 1. DATA UNDERSTANDING
raw = pd.read_csv("data/raw/sales_raw.csv")
n_rows, n_cols = raw.shape
dtypes = raw.dtypes.astype(str).to_dict()

# 2. DATA CLEANING (every change is logged)
log = []
df = raw.copy()
miss = {k: int(v) for k, v in raw.isna().sum().items() if v > 0}
dups = int(df.duplicated().sum())
df = df.drop_duplicates(); log.append(f"Removed {dups} exact duplicate rows.")
df["order_date"] = pd.to_datetime(df["order_date"]); log.append("Converted order_date from text to datetime.")
before = df["region"].copy()
df["region"] = df["region"].str.strip().str.title()
fixed = int((before.notna() & (before != df["region"])).sum())
log.append(f"Standardised region text (trim spaces, Title Case): {fixed} values changed.")
n_reg = int(df["region"].isna().sum()); df["region"] = df["region"].fillna("Unknown")
log.append(f"Filled {n_reg} missing region values with 'Unknown' (ASSUMPTION: region not recoverable).")
n_disc = int(df["discount"].isna().sum()); df["discount"] = df["discount"].fillna(0)
log.append(f"Filled {n_disc} missing discount values with 0 (ASSUMPTION: no discount recorded = none given).")
bad_price = int((df["unit_price"] <= 0).sum()); df = df[df["unit_price"] > 0]
log.append(f"Removed {bad_price} rows with non-positive unit_price (invalid).")
q_out = df["quantity"] > 100; n_q = int(q_out.sum()); df = df[~q_out]
log.append(f"Removed {n_q} rows with quantity > 100 (typical range is 1-5; likely entry errors).")
df["revenue"] = df["quantity"] * df["unit_price"] * (1 - df["discount"])
df["month"] = df["order_date"].dt.to_period("M").astype(str)
df.to_csv("data/processed/sales_clean.csv", index=False)

# 3. EDA
total_rev = df["revenue"].sum(); n_orders = len(df)
aov = df["revenue"].mean(); n_cust = df["customer_id"].nunique()
by_cat = df.groupby("category")["revenue"].sum().sort_values(ascending=False)
by_reg = df.groupby("region")["revenue"].sum().sort_values(ascending=False)
by_pay = df.groupby("payment_method")["revenue"].sum().sort_values(ascending=False)
by_prod = df.groupby("product")["revenue"].sum().sort_values(ascending=False)
monthly = df.groupby("month")["revenue"].sum()
num = ["quantity", "unit_price", "discount", "revenue"]
stats = df[num].describe().round(2)
corr = df[num].corr().round(2)
top_cust = df.groupby("customer_id")["revenue"].sum().sort_values(ascending=False).head(5)
disc_share = (df["discount"] > 0).mean()
h2 = monthly.iloc[-2:].sum() / total_rev

# 4. CHARTS
def save(name): plt.tight_layout(); plt.savefig(CH + name, dpi=130); plt.close()
plt.figure(figsize=(9, 4.5)); plt.plot(monthly.index, monthly.values, marker="o")
plt.title("Monthly Revenue (2025)"); plt.xlabel("Month"); plt.ylabel("Revenue"); plt.xticks(rotation=45); save("1_monthly_revenue.png")
plt.figure(figsize=(7, 4.5)); sns.barplot(x=by_cat.index, y=by_cat.values, color="#4C72B0")
plt.title("Revenue by Category"); plt.ylabel("Revenue"); plt.xlabel(""); save("2_revenue_by_category.png")
plt.figure(figsize=(7, 4.5)); sns.barplot(x=by_reg.index, y=by_reg.values, color="#55A868")
plt.title("Revenue by Region"); plt.ylabel("Revenue"); plt.xlabel(""); save("3_revenue_by_region.png")
plt.figure(figsize=(5.5, 5.5)); plt.pie(by_pay.values, labels=by_pay.index, autopct="%1.1f%%", startangle=90)
plt.title("Revenue Share by Payment Method"); save("4_payment_share.png")
plt.figure(figsize=(7, 4.5)); sns.histplot(df["revenue"], bins=30, color="#C44E52")
plt.title("Distribution of Order Revenue"); plt.xlabel("Revenue per order"); save("5_revenue_histogram.png")
plt.figure(figsize=(7, 4.5)); sns.scatterplot(data=df, x="unit_price", y="revenue", hue="quantity", palette="viridis")
plt.title("Unit Price vs Order Revenue (colour = quantity)"); save("6_price_vs_revenue.png")

# 5-7. REPORT
def tbl(s): return "\n".join(f"| {k} | {v:,.2f} |" for k, v in s.items())
rep = f"""# Retail Sales Analysis Report
*Data: SYNTHETIC practice dataset (generated by src/generate_data.py). Replace with real data before drawing real conclusions.*

## 1. Executive Summary
After cleaning, **{n_orders:,} orders** from **{n_cust} customers** generated **{total_rev:,.0f}** in revenue (average order value **{aov:,.2f}**).
Top category: **{by_cat.index[0]}** ({by_cat.iloc[0]/total_rev:.1%} of revenue). Top region: **{by_reg.index[0]}** ({by_reg.iloc[0]/total_rev:.1%}).
Peak month: **{monthly.idxmax()}** ({monthly.max():,.0f}); lowest month: **{monthly.idxmin()}** ({monthly.min():,.0f}).

## 2. Data Understanding
Raw file: **{n_rows:,} rows x {n_cols} columns**.

| Column | Type | Meaning |
|---|---|---|
| order_id | {dtypes['order_id']} | Order number (duplicated rows share the same id) |
| order_date | {dtypes['order_date']} | Date of order (text in raw file) |
| customer_id | {dtypes['customer_id']} | Customer code |
| region | {dtypes['region']} | Sales region |
| category | {dtypes['category']} | Product category |
| product | {dtypes['product']} | Product name |
| quantity | {dtypes['quantity']} | Units in the order |
| unit_price | {dtypes['unit_price']} | Price per unit |
| discount | {dtypes['discount']} | Discount fraction (0.1 = 10%) |
| payment_method | {dtypes['payment_method']} | How the customer paid |
| revenue (added) | float64 | quantity x unit_price x (1 - discount) |

## 3. Data Quality Findings
Missing values found: {miss}. Exact duplicates: {dups}.

Cleaning log:
""" + "\n".join(f"- {l}" for l in log) + f"""

Rows: {n_rows:,} raw -> {n_orders:,} clean. The original file is untouched; the cleaned copy is data/processed/sales_clean.csv.

## 4. Key Metrics
| Metric | Value |
|---|---|
| Total revenue | {total_rev:,.2f} |
| Orders | {n_orders:,} |
| Average order value | {aov:,.2f} |
| Unique customers | {n_cust} |
| Share of orders with a discount | {disc_share:.1%} |

Revenue by category:

| Category | Revenue |
|---|---|
{tbl(by_cat)}

Revenue by region:

| Region | Revenue |
|---|---|
{tbl(by_reg)}

Top 5 products by revenue:

| Product | Revenue |
|---|---|
{tbl(by_prod.head(5))}

Top 5 customers by revenue:

| Customer | Revenue |
|---|---|
{tbl(top_cust)}

Descriptive statistics:

{stats.to_markdown()}

Correlations:

{corr.to_markdown()}

## 5. Visualizations
1. ![](charts/1_monthly_revenue.png) Revenue over time - shows seasonality.
2. ![](charts/2_revenue_by_category.png) Which categories earn the most.
3. ![](charts/3_revenue_by_region.png) Regional performance.
4. ![](charts/4_payment_share.png) Payment preferences.
5. ![](charts/5_revenue_histogram.png) Shape of order sizes (is it skewed?).
6. ![](charts/6_price_vs_revenue.png) How price and quantity relate to revenue.

## 6. Insights and Recommendations
- **Seasonality:** the last two months of the year account for {h2:.1%} of annual revenue. Plan inventory and promotions ahead of Nov-Dec.
- **Category focus:** {by_cat.index[0]} leads and {by_cat.index[-1]} is lowest. Protect stock of the leader; review pricing or promotion for the laggard.
- **Region gaps:** {by_reg.index[0]} vs {by_reg.index[-1]} shows an uneven spread. Investigate whether the gap comes from customer count, pricing or marketing.
- **Data entry:** quantity outliers, negative prices, duplicates and inconsistent region text all appeared. Add input validation at the source.

## 7. Limitations and Assumptions
- Dataset is synthetic; patterns reflect how it was generated, not a real business.
- Missing discount treated as 0 and missing region as 'Unknown' (assumptions).
- Quantity > 100 treated as error; with real data, confirm with the data owner first.
- One year of data, so year-over-year trends cannot be assessed. Correlation does not imply causation.
"""
open("outputs/report.md", "w").write(rep)
print("Done. Revenue:", round(total_rev, 2), "| rows:", n_rows, "->", n_orders)
print("Cleaning log:"); [print(" -", l) for l in log]
print(by_cat.round(0).to_dict(), by_reg.round(0).to_dict(), round(h2, 3))
